import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';

const source=readFileSync('chat-dhcp/scenario-diagnostic.js','utf8');
const html=readFileSync('chat-dhcp/index.html','utf8');
const js=readFileSync('chat-dhcp/app.js','utf8');
const checkIds=[...source.matchAll(/\{id:'([^']+)',label:/g)].map(m=>m[1]);
assert.equal(checkIds.length,14,'Le scénario technique témoin conserve 14 contrôles');
assert.match(source,/requiredChecks:\['relay','server'\]/);
assert.match(source,/VLAN 30/);
assert.match(html,/id="conversation"/);
assert.match(html,/id="suggestions"/);
assert.match(html,/id="send"/);
assert.match(html,/id="restart"/);
assert.doesNotMatch(html,/diagcore\.js|engine-host|ipconfig/i,'Aucune interface technique ne doit apparaître dans le chat');
assert.match(js,/const questions=/);
assert.match(js,/question|answer|reply/);
assert.match(js,/VLAN 10 fonctionne/);
assert.match(js,/VLAN 30/);
assert.match(js,/Depuis ce matin/);
assert.match(js,/selected=q/);
assert.match(js,/asked\.add\(q\.id\)/);
assert.doesNotMatch(js,/fetch\(|webllm|transformers|nlpjs|\.click\(\)/i,'Aucun LLM ni pilotage détourné de l interface technique');
assert.doesNotMatch(js,/Le problème est résolu|Incident résolu/,'La conversation ne doit pas annoncer de réparation');
console.log('OK : dialogue DHCP contrôlé, informations du scénario et absence de commandes techniques dans le chat.');
